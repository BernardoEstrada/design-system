export type IconSource = "lucide" | "lab";
export { iconCategories, type IconCategory };

export interface IconEntry {
  /** Kebab-case name, e.g. "apple-core". Pass it to DynamicIcon. */
  name: IconName;
  source: IconSource;
  /** Category ids, e.g. ["food-beverage"]. Empty until the search index loads. */
  categories: string[];
  /** Name parts: ["apple", "core"] */
  words: string[];
  compact: string;
  tags: string[];
  /** Former names, e.g. "trash-2" for trash */
  aliases: string;
  categoryText: string;
}

// Generated by scripts/gen-icons.mjs:
// { c: [category ids], i: { name: ["tag|tag", [category index], [aliases]?] } }
interface SearchIndex {
  c: string[];
  i: Record<string, [string, number[], string[]?]>;
}

// The index is ~65 KB gzipped, so it loads in its own chunk when a picker mounts.
// Until then, search matches names only.
const emptyIndex: SearchIndex = { c: [], i: {} };
let loadedIndex = emptyIndex;
let indexPromise: Promise<SearchIndex> | undefined;
const loadIndex = () =>
  (indexPromise ??= import("../../icons/search-index.json").then(
    (m) => (loadedIndex = m.default as unknown as SearchIndex),
  ));

const categoryTitles = new Map<string, string>(iconCategories.map((c) => [c.id, c.title.toLowerCase()]));

const catalogs = new WeakMap<SearchIndex, IconEntry[]>();

function entry(name: IconName, source: IconSource, index: SearchIndex): IconEntry {
  const [tags = "", cats = [], aliases = []] = index.i[name] ?? [];
  const categories = cats.map((c) => index.c[c]);
  return {
    name,
    source,
    categories,
    words: name.split("-"),
    compact: name.replace(/-/g, ""),
    tags: tags ? tags.toLowerCase().split("|") : [],
    aliases: aliases.join(" "),
    categoryText: categories.map((c) => `${c} ${categoryTitles.get(c) ?? ""}`).join(" "),
  };
}

function getCatalog(index: SearchIndex): IconEntry[] {
  let catalog = catalogs.get(index);
  if (!catalog) {
    catalog = [
      ...lucideCanonicalNames.map((n) => entry(n, "lucide", index)),
      ...labIconNames.map((n) => entry(n, "lab", index)),
    ].sort((a, b) => a.name.localeCompare(b.name));
    catalogs.set(index, catalog);
  }
  return catalog;
}

/** Load the search index now, so `searchIcons` also matches tags, categories and aliases. */
export async function preloadIconSearch(): Promise<void> {
  await loadIndex();
}
/** @deprecated Use `preloadIconSearch`. */
export const preloadIconTags = preloadIconSearch;

/** How well one search term matches. Lower is better; undefined means no match. */
function termRank(e: IconEntry, t: string): number | undefined {
  if (e.words.includes(t)) return 1; // a whole word of the name
  if (e.compact.includes(t)) return 2; // part of the name
  if (e.aliases.includes(t)) return 3; // a former name
  // Lucide lists an icon's tags roughly by relevance, so earlier tags rank higher.
  const whole = e.tags.findIndex((tag) => tag === t || tag.split(" ").includes(t));
  if (whole >= 0) return 4 + Math.min(whole, 9) / 10; // a whole tag
  if (e.categoryText.includes(t)) return 5; // a category
  const partial = e.tags.findIndex((tag) => tag.includes(t));
  if (partial >= 0) return 6 + Math.min(partial, 9) / 10; // part of a tag
  return undefined;
}

function score(e: IconEntry, query: string, terms: string[]): number | undefined {
  let worst = 0;
  for (const t of terms) {
    const r = termRank(e, t);
    if (r === undefined) return undefined;
    worst = Math.max(worst, r);
  }
  const q = query.replace(/[\s-]+/g, "");
  if (e.compact === q) return 0;
  if (e.compact.startsWith(q)) return Math.min(worst, 1);
  return worst;
}

export interface SearchIconsOptions {
  sources?: IconSource[];
  /** Only icons in this category. */
  category?: IconCategory | string | null;
}

/**
 * Search Lucide and Lab icons. Matches names first, then former names, tags and
 * categories once the search index has loaded (see `preloadIconSearch`).
 */
export function searchIcons(query: string, options: SearchIconsOptions | IconSource[] = {}): IconEntry[] {
  const { sources = ["lucide", "lab"], category } = Array.isArray(options) ? { sources: options } : options;
  const all = getCatalog(loadedIndex).filter(
    (e) => sources.includes(e.source) && (!category || e.categories.includes(category)),
  );
  const q = query.trim().toLowerCase();
  if (!q) return all;
  const terms = q.split(/[\s-]+/).filter(Boolean);
  return all
    .map((e) => ({ e, s: score(e, q, terms) }))
    .filter((r): r is { e: IconEntry; s: number } => r.s !== undefined)
    .sort((a, b) => a.s - b.s || a.e.name.localeCompare(b.e.name))
    .map((r) => r.e);
}

// Matches Tailwind's `sm` breakpoint: below it the picker opens as a bottom sheet.
const SMALL_SCREEN = "(max-width: 639px)";
function subscribeSmallScreen(onChange: () => void) {
  const mq = window.matchMedia(SMALL_SCREEN);
  mq.addEventListener("change", onChange);
  return () => mq.removeEventListener("change", onChange);
}
function useSmallScreen(): boolean {
  return useSyncExternalStore(
    subscribeSmallScreen,
    () => window.matchMedia(SMALL_SCREEN).matches,
    () => false,
  );
}

// Same-size placeholder while an icon chunk loads, so the grid doesn't jump.
const CellPlaceholder = () => <span className="bg-base-content/10 size-5 rounded" aria-hidden />;

// ─── Panel ──────────────────────────────────────────────────────────────────

interface PanelProps {
  value: string | null;
  onSelect: (name: string | null) => void;
  sources: IconSource[];
  clearable: boolean;
  maxResults: number;
  loadMore: boolean;
  categoryFilter: boolean;
  columns: number;
  /** Larger, touch-sized controls and a grid that fills the available width. */
  touch: boolean;
  color: string | null;
  onColorChange: (color: string | null) => void;
  colorPicker: boolean;
  colorPresets?: Array<ColorPreset | string>;
  /** Focus the search box when this becomes true. */
  autoFocus: boolean;
}

function IconPickerPanel({
  value,
  onSelect,
  sources,
  clearable,
  maxResults,
  loadMore,
  categoryFilter,
  columns,
  touch,
  color,
  onColorChange,
  colorPicker,
  colorPresets,
  autoFocus,
}: PanelProps) {
  const gridRef = useRef<HTMLDivElement>(null);
  const [query, setQuery] = useState("");
  const [filter, setFilter] = useState<IconSource | "all">("all");
  const [category, setCategory] = useState("");
  const deferredQuery = useDeferredValue(query);
  const inputRef = useRef<HTMLInputElement>(null);
  const cellRefs = useRef<Array<HTMLButtonElement | null>>([]);

  useEffect(() => {
    if (autoFocus) inputRef.current?.focus();
  }, [autoFocus]);

  // Re-run the search once the index arrives.
  const [indexReady, setIndexReady] = useState(loadedIndex !== emptyIndex);
  useEffect(() => {
    if (indexReady) return;
    let ignore = false;
    loadIndex().then(() => {
      if (!ignore) setIndexReady(true);
    });
    return () => {
      ignore = true;
    };
  }, [indexReady]);

  // Joined into a string so a new `sources` array each render doesn't re-run the search.
  const sourcesKey = (filter === "all" ? sources : [filter]).join(",");
  const results = useMemo(
    () => searchIcons(deferredQuery, { sources: sourcesKey.split(",") as IconSource[], category }),
    [deferredQuery, sourcesKey, category, indexReady],
  );

  // Categories that have at least one icon in the active icon sets.
  const categories = useMemo(() => {
    if (!indexReady) return [];
    const active = sourcesKey.split(",");
    const used = new Set(
      getCatalog(loadedIndex)
        .filter((e) => active.includes(e.source))
        .flatMap((e) => e.categories),
    );
    return iconCategories.filter((c) => used.has(c.id));
  }, [indexReady, sourcesKey]);

  // The visible count resets whenever the search, icon set or category changes.
  const searchKey = `${deferredQuery}|${sourcesKey}|${category}`;
  const [page, setPage] = useState({ key: searchKey, limit: maxResults });
  const limit = page.key === searchKey ? page.limit : maxResults;
  const shown = results.slice(0, limit);
  const hasMore = results.length > shown.length;

  // After "Load more", move focus to the first new icon (the button may disappear).
  const focusAfterLoad = useRef<number | null>(null);
  useEffect(() => {
    if (focusAfterLoad.current === null) return;
    cellRefs.current[focusAfterLoad.current]?.focus();
    focusAfterLoad.current = null;
  }, [limit]);
  const showMore = () => {
    focusAfterLoad.current = shown.length;
    setPage({ key: searchKey, limit: limit + maxResults });
  };

  const focusCell = (i: number) => cellRefs.current[Math.max(0, Math.min(i, shown.length - 1))]?.focus();

  const onInputKey = (e: KeyboardEvent<HTMLInputElement>) => {
    if (e.key === "ArrowDown" && shown.length) {
      e.preventDefault();
      focusCell(0);
    } else if (e.key === "Enter" && shown.length) {
      e.preventDefault();
      onSelect(shown[0].name);
    }
  };

  const onCellKey = (e: KeyboardEvent<HTMLButtonElement>, i: number) => {
    // Read the column count from the layout, since touch mode lets the grid decide it.
    const cols = gridRef.current
      ? getComputedStyle(gridRef.current).gridTemplateColumns.split(" ").length
      : columns;
    const moves: Record<string, number> = { ArrowRight: 1, ArrowLeft: -1, ArrowDown: cols, ArrowUp: -cols };
    const step = moves[e.key];
    if (step === undefined) return;
    e.preventDefault();
    if (i + step < 0) inputRef.current?.focus();
    else focusCell(i + step);
  };

  return (
    <div className="flex flex-col gap-2">
      {/* 16px text on touch screens stops iOS from zooming in when the field is focused. */}
      <label className={cx("input w-full", touch ? "text-base" : "input-sm")}>
        <Search className="size-4 opacity-60" aria-hidden />
        <input
          ref={inputRef}
          type="search"
          placeholder="Search icons…"
          aria-label="Search icons"
          value={query}
          onChange={(e) => setQuery(e.target.value)}
          onKeyDown={onInputKey}
        />
      </label>

      {(sources.length > 1 || categoryFilter) && (
        <div className="flex flex-wrap items-center gap-2">
          {sources.length > 1 && (
            <div className="join" role="group" aria-label="Icon set">
              {(["all", ...sources] as const).map((s) => (
                <button
                  key={s}
                  type="button"
                  className={cx("btn join-item", touch ? "btn-sm" : "btn-xs", filter === s && "btn-active")}
                  aria-pressed={filter === s}
                  onClick={() => setFilter(s)}
                >
                  {s === "all" ? "All" : s === "lucide" ? "Lucide" : "Lab"}
                </button>
              ))}
            </div>
          )}
          {categoryFilter && (
            <select
              className={cx("select min-w-24 flex-1", touch ? "select-sm text-base" : "select-xs")}
              aria-label="Category"
              value={category}
              disabled={!indexReady}
              onChange={(e) => setCategory(e.target.value)}
            >
              <option value="">{indexReady ? "All categories" : "Loading categories…"}</option>
              {categories.map((c) => (
                <option key={c.id} value={c.id}>
                  {c.title}
                </option>
              ))}
            </select>
          )}
        </div>
      )}

      {shown.length ? (
        <div
          ref={gridRef}
          className={cx("grid gap-1 overflow-y-auto", touch ? "max-h-[45dvh]" : "max-h-64")}
          style={{
            gridTemplateColumns: touch
              ? "repeat(auto-fill, minmax(2.75rem, 1fr))"
              : `repeat(${columns}, minmax(0, 1fr))`,
          }}
        >
          {shown.map(({ name }, i) => (
            <button
              key={name}
              ref={(el) => {
                cellRefs.current[i] = el;
              }}
              type="button"
              title={name}
              aria-label={name}
              aria-pressed={name === value}
              className={cx(
                "btn btn-square",
                touch ? "size-11 justify-self-center" : "btn-sm",
                // With a custom color, mark the selection with a ring so the icon keeps its color.
                name === value ? (color ? "btn-ghost ring-primary bg-base-200 ring-2" : "btn-primary") : "btn-ghost",
              )}
              onClick={() => onSelect(name)}
              onKeyDown={(e) => onCellKey(e, i)}
            >
              {/* Color goes on the icon itself: some themes set their own text color on ghost buttons. */}
              <DynamicIcon
                name={name}
                className={touch ? "size-6" : "size-5"}
                style={color ? { color } : undefined}
                aria-hidden
                fallback={CellPlaceholder}
              />
            </button>
          ))}
          {loadMore && hasMore && (
            <button type="button" className="btn btn-ghost btn-sm col-span-full mt-1" onClick={showMore}>
              Load {Math.min(maxResults, results.length - shown.length)} more
            </button>
          )}
        </div>
      ) : (
        <p className="py-6 text-center text-sm opacity-70">
          {query ? `No icons match “${query}”` : "No icons"}
          {category ? " in this category" : ""}.
        </p>
      )}

      <div className="flex items-center gap-2 text-xs">
        <span aria-live="polite" className="opacity-70">
          {hasMore
            ? `Showing ${shown.length} of ${results.length}.${loadMore ? "" : " Keep typing to narrow."}`
            : `${results.length} icon${results.length === 1 ? "" : "s"}`}
        </span>
        <div className="ml-auto flex items-center gap-1">
          {clearable && value && (
            <button type="button" className="btn btn-ghost btn-xs opacity-70" onClick={() => onSelect(null)}>
              Clear
            </button>
          )}
          {colorPicker && (
            // Opens upward: the footer sits at the bottom of the panel (and of the screen on phones).
            <ColorPicker
              size="sm"
              aria-label="Icon color"
              allowNone
              value={color}
              onChange={onColorChange}
              presets={colorPresets}
              align="end"
              position="top"
            />
          )}
        </div>
      </div>
    </div>
  );
}

// ─── Picker ─────────────────────────────────────────────────────────────────

interface IconPickerProps {
  /** Selected icon's kebab-case name, e.g. "apple-core". Render it with DynamicIcon. */
  value?: string | null;
  defaultValue?: string | null;
  onChange?: (name: string | null) => void;
  /** Which icon sets to offer. Default: both. */
  sources?: IconSource[];
  label?: string;
  hint?: string;
  error?: string;
  placeholder?: string;
  clearable?: boolean;
  /** Render the search panel directly instead of behind a button. */
  inline?: boolean;
  /** Icons rendered at a time; also the "Load more" page size. Default 160. */
  maxResults?: number;
  /** Show a "Load more" button below the results. When false, the rest are only reachable by searching. Default true. */
  loadMore?: boolean;
  /** Show the category dropdown. Default true. */
  categoryFilter?: boolean;
  /** Show a color picker that tints every icon in the picker. Default true. */
  colorPicker?: boolean;
  /** Icon color (any CSS color), or null for the current text color. */
  color?: string | null;
  defaultColor?: string | null;
  onColorChange?: (color: string | null) => void;
  /** Presets for the color picker. Defaults to ColorPicker's palette. */
  colorPresets?: Array<ColorPreset | string>;
  columns?: number;
  className?: string;
}

export function IconPicker({
  value: valueProp,
  defaultValue = null,
  onChange,
  sources = ["lucide", "lab"],
  label,
  hint,
  error,
  placeholder = "Choose an icon",
  clearable = true,
  inline = false,
  maxResults = 160,
  loadMore = true,
  categoryFilter = true,
  colorPicker = true,
  color: colorProp,
  defaultColor = null,
  onColorChange,
  colorPresets,
  columns = 8,
  className = "",
}: IconPickerProps) {
  const [internal, setInternal] = useState<string | null>(defaultValue);
  const [open, setOpen] = useState(false);
  const value = valueProp === undefined ? internal : valueProp;
  const [internalColor, setInternalColor] = useState<string | null>(defaultColor);
  const color = colorProp === undefined ? internalColor : colorProp;
  const changeColor = (c: string | null) => {
    if (colorProp === undefined) setInternalColor(c);
    onColorChange?.(c);
  };

  const select = (name: string | null) => {
    if (valueProp === undefined) setInternal(name);
    onChange?.(name);
    setOpen(false);
  };

  const small = useSmallScreen();
  const panelProps = {
    value,
    onSelect: select,
    sources,
    clearable,
    maxResults,
    loadMore,
    categoryFilter,
    columns,
    touch: small,
    color,
    onColorChange: changeColor,
    colorPicker,
    colorPresets,
  };

  const triggerContent: ReactNode = (
    <>
      <span className="flex items-center gap-2">
        {value && (
          <DynamicIcon name={value as IconName} className="size-4" style={{ color: color ?? undefined }} aria-hidden />
        )}
        <span className={value ? undefined : "opacity-60"}>{value ?? placeholder}</span>
      </span>
      <ChevronDown className="size-4 opacity-60" aria-hidden />
    </>
  );
  const triggerClassName = cx("justify-between font-normal", error && "border-error");

  let picker: ReactNode;
  if (inline) {
    picker = (
      <div className={cx("card bg-base-100 border-base-300 w-full border p-3 sm:w-80", className)}>
        <IconPickerPanel {...panelProps} autoFocus={false} />
      </div>
    );
  } else if (small) {
    // Bottom sheet on phones. No autofocus, so the keyboard doesn't cover the icons.
    picker = (
      <div className={className}>
        <Button
          type="button"
          variant="outline"
          aria-haspopup="dialog"
          aria-expanded={open}
          className={cx("w-full", triggerClassName)}
          onClick={() => setOpen(true)}
        >
          {triggerContent}
        </Button>
        <Modal open={open} onClose={() => setOpen(false)} position="bottom" title={label ?? placeholder}>
          <IconPickerPanel {...panelProps} autoFocus={false} />
        </Modal>
      </div>
    );
  } else {
    picker = (
      <Dropdown
        open={open}
        onOpenChange={setOpen}
        triggerVariant="outline"
        triggerClassName={triggerClassName}
        className={className}
        trigger={triggerContent}
      >
        <div className="card bg-base-100 w-80 p-3 shadow-lg">
          <IconPickerPanel {...panelProps} autoFocus={open} />
        </div>
      </Dropdown>
    );
  }

  return (
    <Field label={label} error={error} hint={hint}>
      {picker}
    </Field>
  );
}
