// Generates the icon entry points under src/icons/:
//   index.ts        → lucide-react + @lucide/lab   (@bernardoestrada/design-system/icons)
//   lab.ts          → @lucide/lab icons as React components
//   <pack>.ts       → one re-export per react-icons pack (@bernardoestrada/design-system/icons/fa, …)
//   react-icons.ts  → react-icons' shared helpers (IconContext, IconBase, …)
//
// Runs before every build so new packs / lab icons show up after a dependency upgrade.
import { mkdirSync, readdirSync, rmSync, writeFileSync, existsSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "src/icons");
const require = createRequire(import.meta.url);
const header = "// Generated by scripts/gen-icons.mjs. Do not edit.\n";

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

// ── @lucide/lab → React components ────────────────────────────────────────
const lab = await import("@lucide/lab");
const lucide = await import("lucide-react");
const pascal = (s) => s[0].toUpperCase() + s.slice(1);

// Lucide keeps promoting lab icons into the main set. Prefer the main version
// when it already exists so the two don't collide.
const labNames = Object.keys(lab)
  .filter((k) => /^[a-z][a-zA-Z0-9]*$/.test(k) && Array.isArray(lab[k]))
  .filter((k) => !(pascal(k) in lucide))
  .sort();
const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").replace(/([a-zA-Z])([0-9])/g, "$1-$2").toLowerCase();

const labLines = [
  header,
  'import { createLucideIcon } from "lucide-react";',
  `import {\n${labNames.map((n) => `  ${n},`).join("\n")}\n} from "@lucide/lab";`,
  "",
  ...labNames.flatMap((n) => {
    const C = pascal(n);
    return [
      `export const ${C} = /* @__PURE__ */ createLucideIcon("${kebab(n)}", ${n});`,
      `export { ${C} as ${C}Icon };`,
    ];
  }),
  "",
];
writeFileSync(join(outDir, "lab.ts"), labLines.join("\n"));

// Lab icons are re-exported by name: a named export always wins over
// `export *`, so a lucide-react release that adds the same name can't make
// the icon ambiguous (which would silently drop it).
const labExports = labNames.flatMap((n) => [pascal(n), `${pascal(n)}Icon`]);
writeFileSync(
  join(outDir, "index.ts"),
  `${header}export * from "lucide-react";\nexport {\n${labExports.map((n) => `  ${n},`).join("\n")}\n} from "./lab";\n`,
);

// ── react-icons packs ─────────────────────────────────────────────────────
const riDir = dirname(require.resolve("react-icons"));
const packs = readdirSync(riDir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && d.name !== "lib" && existsSync(join(riDir, d.name, "index.mjs")))
  .map((d) => d.name)
  .sort();

for (const pack of packs) {
  writeFileSync(join(outDir, `${pack}.ts`), `${header}export * from "react-icons/${pack}";\n`);
}
writeFileSync(join(outDir, "react-icons.ts"), `${header}export * from "react-icons";\n`);

// Read by vite.config.ts to build one entry per file.
writeFileSync(
  join(outDir, "entries.json"),
  JSON.stringify(["index", "lab", "react-icons", ...packs], null, 2) + "\n",
);

console.log(`icons: ${labNames.length} lab icons, ${packs.length} react-icons packs`);
